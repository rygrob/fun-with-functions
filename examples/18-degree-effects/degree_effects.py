"""What raising the degree of a polynomial buys, for sin, log2 and tanh.

Each added Horner step costs about the same everywhere. What it buys depends
on the function and on the form it's written in:

  fit error        falls at a rate set by the function's nearest singularity
                   in the complex plane (Bernstein's ellipse): rho^-n, or
                   faster than any rho for a function with none
  rounding floor   f32 arithmetic stops the error near 2^-24, whatever the
                   degree. Past that a higher degree only costs
  structure        a form that can't be right near a zero, or past where a
                   polynomial runs off, is limited by the form rather than
                   the degree

  sin_radians   plain odd fit of sin x on [-pi, pi]        (03)
  sin_split     factored, the zeros on split pi            (05)
  sin_turns     factored in turns, exact zeros             (06)
  log2_plain    e + u P(u) on [1, 2)                       (11)
  log2_fold     the same, folded at 1.5                    (11)
  tanh_clamp    odd fit of tanh x, input clamped           (12)
  tanh_sigmoid  s / sqrt(1 + s^2), s = x R(x^2), clamped   (12)

Every Chebyshev fit is a projection, as on the slides. Exact errors and
timings come from degree_bench.cpp, saved in results/. This script emits its
header and reads what it wrote; run alone, it reads the saved results. Those
are from an M2 Pro on power: indicative elsewhere.

Usage:
    python degree_effects.py                       # tables and plots from results/
    python degree_effects.py --no-show             # just write the PNGs
    python degree_effects.py --emit-cpp > degree_approx.hpp
"""

import argparse
import math
import re
import statistics
import sys
from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np
from numpy.polynomial import Chebyshev

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))  # for ../common
from common import cppgen, fit, harness, log2poly, plots, tanhpoly

RESULTS = Path(__file__).parent / "results"
OUT_DIR = Path(__file__).parent / "out"

# name -> label, degrees, the emitter.
FAMILIES = {
    "sin_radians": ("sin, plain fit", [5, 7, 9, 11, 13, 15], cppgen.emit_cheb_vanilla),
    "sin_split": ("sin, split pi", [5, 7, 9, 11, 13, 15, 17], cppgen.emit_cheb_split),
    "sin_turns": ("sin, turns", [5, 7, 9, 11, 13, 15, 17], cppgen.emit_cheb_turns),
    "log2_plain": ("log2, [1, 2)", [3, 5, 7, 9, 11, 13], lambda d: cppgen.emit_log2(d, None)),
    "log2_fold": ("log2, fold 1.5", [3, 4, 5, 6, 7, 8, 9, 10, 11], lambda d: cppgen.emit_log2(d, 1.5)),
    "tanh_clamp": ("tanh, polynomial", [5, 7, 9, 11, 13, 15, 17], cppgen.emit_tanh_clamp),
    "tanh_sigmoid": ("tanh, sigmoid", [3, 5, 7, 9, 11, 13],
                     lambda d: cppgen.emit_tanh_sigmoid(d, tanhpoly.fit_sigmoid_cheb(d), f"sigmoid_cheb_tanh_{d}", 9.0)),
}
REFERENCE = {"sin_radians": "std::sin", "sin_split": "std::sin", "sin_turns": "std::sin", "log2_plain": "std::log2",
             "log2_fold": "std::log2", "tanh_clamp": "std::tanh", "tanh_sigmoid": "std::tanh"}

HORNER_STEP = re.compile(r"^\s+\w+ = \w+ \* \w+ \+ T\(", re.M)


# ---------------------------------------------------------------------------
# The header
# ---------------------------------------------------------------------------

def emit_cpp():
    fit.set_method("projection")
    calls, parts = [], []
    for family, (_, degrees, emit) in FAMILIES.items():
        for d in degrees:
            name, code = emit(d)
            parts.append(code)
            calls.append(f'    f(Family::{family}, "{family}", {d}, "{name}", '
                         f'[](float x) {{ return {name}<float>(x); }}, [](double x) {{ return {name}<double>(x); }});')
    return "\n".join([
        "#pragma once",
        "// Generated by examples/18-degree-effects/degree_effects.py --emit-cpp -- do not edit.",
        "",
        "#include <algorithm>\n#include <bit>\n#include <cmath>\n#include <cstdint>\n#include <type_traits>",
        "",
        "namespace adc {",
        "",
        "enum class Family { " + ", ".join(FAMILIES) + " };",
        "",
        cppgen.bit_helpers(),
        *parts,
        "/// Calls f(family, family name, degree, name, float fn, double fn) per method.",
        "template<typename F>",
        "inline void for_each_degree_method(F&& f)",
        "{",
        *calls,
        "}",
        "",
        "} // namespace adc",
        "",
    ])


def horner_steps():
    """Multiply-adds in each method's polynomial: what a degree actually costs."""
    fit.set_method("projection")
    return {(family, d): len(HORNER_STEP.findall(emit(d)[1]))
            for family, (_, degrees, emit) in FAMILIES.items() for d in degrees}


# ---------------------------------------------------------------------------
# Results
# ---------------------------------------------------------------------------

def read_results():
    """{(family, degree): row}, timings the median over the saved launches.
    Degree 0 is the library's own function."""
    rows = {}
    for line in (RESULTS / "errors.txt").read_text().splitlines():
        _, family, d, name, *v = line.split()
        rows[(family, int(d))] = dict(zip(("abs", "rel", "ulp", "at", "abs64", "rel64"), map(float, v)), name=name)
    launches = {}
    for line in (RESULTS / "timing.txt").read_text().splitlines():
        _, family, d, _, *v = line.split()
        launches.setdefault((family, int(d)), []).append(list(map(float, v)))
    for key, runs in launches.items():
        rows.setdefault(key, {}).update(zip(("buffer", "sample", "feedback"), map(statistics.median, zip(*runs))))
    return rows


def reference(rows, family):
    """The library's row: sin_split shares sin_radians', log2_plain log2_fold's,
    tanh_clamp tanh_sigmoid's."""
    return rows[({"sin_split": "sin_radians", "log2_plain": "log2_fold", "tanh_clamp": "tanh_sigmoid"}.get(family, family), 0)]


def print_tables(rows, steps):
    for family, (label, degrees, _) in FAMILIES.items():
        ref = reference(rows, family)
        print(f"\n{label}  ({REFERENCE[family]}: abs {ref['abs']:.3g}, ULP {ref['ulp']:.3g}, "
              f"{ref['buffer']:.3f} / {ref['sample']:.3f} / {ref['feedback']:.2f} ns)")
        print(f"  {'deg':>3} {'steps':>5} {'abs f64':>9} {'abs f32':>9} {'bits':>5} {'rel f32':>9} {'max ULP':>9}"
              f" {'buffer':>7} {'sample':>7} {'fback':>6} {'x std':>6}")
        for d in degrees:
            r = rows[(family, d)]
            print(f"  {d:>3} {steps[(family, d)]:>5} {r['abs64']:>9.2e} {r['abs']:>9.2e} {-math.log2(r['abs']):>5.1f}"
                  f" {r['rel']:>9.2e} {r['ulp']:>9.3g} {r['buffer']:>7.3f} {r['sample']:>7.3f} {r['feedback']:>6.2f}"
                  f" {ref['sample'] / r['sample']:>5.1f}x")


def print_marginal(rows, steps):
    """What one more Horner step buys and costs: fit bits (f64), bits you can
    keep (f32), and the time, per step, between neighbouring degrees."""
    print("\nPer Horner step: bits of abs error, f64 fit and f32 kept; ns in each loop")
    print(f"  {'':<18} {'deg':>7} {'f64 bits':>9} {'f32 bits':>9} {'buffer':>7} {'sample':>7} {'fback':>6}")
    for family, (label, degrees, _) in FAMILIES.items():
        for a, b in zip(degrees, degrees[1:]):
            ra, rb = rows[(family, a)], rows[(family, b)]
            n = steps[(family, b)] - steps[(family, a)]
            print(f"  {label:<18} {a:>3}-{b:<3} {math.log2(ra['abs64'] / rb['abs64']) / n:>9.2f}"
                  f" {math.log2(ra['abs'] / rb['abs']) / n:>9.2f} {(rb['buffer'] - ra['buffer']) / n:>7.3f}"
                  f" {(rb['sample'] - ra['sample']) / n:>7.3f} {(rb['feedback'] - ra['feedback']) / n:>6.2f}")


# ---------------------------------------------------------------------------
# Why: the rate the singularities allow
# ---------------------------------------------------------------------------

def rho(z, a, b):
    """Bernstein's rho for a singularity at z, fitting on [a, b]: the ellipse
    with foci a, b through z. The series falls like rho^-n."""
    t = (2 * z - a - b) / (b - a)
    w = abs(t + np.sqrt(t * t - 1 + 0j))
    return max(w, 1 / w)


def measured_rate(fn, a, b, lo, hi):
    """rho from the series itself: the mean fall per degree of |a_k| between
    degrees lo and hi."""
    c = np.abs(Chebyshev.interpolate(fn, 256, domain=[a, b]).coef)
    return (c[lo] / c[hi]) ** (1 / (hi - lo))


def print_rates():
    print("\nWhy: Chebyshev series rate per degree, measured vs. the nearest singularity")
    print(f"  {'':<34} {'nearest':>12} {'predicted':>10} {'measured':>9} {'bits/deg':>9}")
    for label, fn, a, b, z, where, lo, hi in [
        ("log2 m / u on [-1/4, 1/2) (fold)", log2poly.log2_quotient, -0.25, 0.5, -1.0, "u = -1", 4, 14),
        ("log2 m / u on [0, 1) (plain)", log2poly.log2_quotient, 0.0, 1.0, -1.0, "u = -1", 4, 14),
        ("tanh x on [-2.8, 2.8]", np.tanh, -2.8, 2.8, 0.5j * math.pi, "x = i pi/2", 5, 25),
        ("tanh x on [-4, 4]", np.tanh, -4.0, 4.0, 0.5j * math.pi, "x = i pi/2", 9, 41),
    ]:
        r = rho(z, a, b)
        m = measured_rate(fn, a, b, lo, hi)
        print(f"  {label:<34} {where:>12} {r:>10.2f} {m:>9.2f} {math.log2(r):>9.2f}")
    print("\n  No singularity at all (entire), so the fall per degree keeps speeding up:")
    for label, fn, a, b, deg in [("sin x on [-pi, pi]", np.sin, -math.pi, math.pi, range(5, 18, 2)),
                                 ("sinh x / x in v = x^2, [0, 3.4^2]", tanhpoly.sinh_quotient_v, 0.0, 3.4**2, range(1, 8))]:
        c = np.abs(Chebyshev.interpolate(fn, 256, domain=[a, b]).coef)
        print(f"    {label}: bits gained per coefficient, " + "  ".join(
            f"{k}: {math.log2(c[k] / c[k + (2 if a < 0 else 1)]):.1f}" for k in deg))


# ---------------------------------------------------------------------------
# Plots
# ---------------------------------------------------------------------------

def plot_effects(rows, steps):
    fig, axes = plt.subplots(1, 3, figsize=(14, 4.6))
    for color, (family, (label, degrees, _)) in zip(plots.SERIES, FAMILIES.items()):
        n = [steps[(family, d)] for d in degrees]
        axes[0].semilogy(n, [rows[(family, d)]["abs"] for d in degrees], "o-", color=color, ms=3, label=label)
        axes[0].semilogy(n, [rows[(family, d)]["abs64"] for d in degrees], ":", color=color, lw=1)
        axes[1].semilogy(n, [rows[(family, d)]["ulp"] for d in degrees], "o-", color=color, ms=3, label=label)
        axes[2].plot(n, [rows[(family, d)]["feedback"] for d in degrees], "o-", color=color, ms=3, label=label)
    axes[0].set(title="Max absolute error (dotted: fit alone, f64)", xlabel="Horner steps")
    axes[0].axhline(2.0**-24, color=plots.TRUTH, lw=0.8)
    axes[1].set(title="Max ULP, every float", xlabel="Horner steps")
    axes[2].set(title="Feedback loop, ns per sample", xlabel="Horner steps")
    axes[0].legend(fontsize=8)
    fig.tight_layout()
    return fig


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--emit-cpp", action="store_true", help="print degree_approx.hpp")
    parser.add_argument("--no-show", action="store_true", help="save figures without opening a window")
    args = parser.parse_args()
    if args.emit_cpp:
        print(emit_cpp())
        return
    steps = horner_steps()
    rows = read_results()
    print_tables(rows, steps)
    print_marginal(rows, steps)
    print_rates()
    harness.save_figures(OUT_DIR, "degree_effects", {"": plot_effects(rows, steps)}, show=not args.no_show)


if __name__ == "__main__":
    main()
