def emit_cheb_phase(degree):
    """Turns polynomial computed from a 32-bit phase with every factor taken
    from the integer, so each keeps full relative precision near its zero:
        x     = phase / 2^32               (zero at phase 0)
        x - 1 = -(2^32 - phase) / 2^32     (zero at the wrap; 0u - phase is exact)
        u     = (phase - 2^31) / 2^32      (zero at half a turn; signed, exact)
    The table lookups get this for free by using integer bits; a polynomial
    has to ask for it."""
    from .sinpoly import fit_cheb_turns
    name = f"cheb_phase_sin_{degree}"
    s = lit(2.0 ** -32)
    body = [
        f"    constexpr auto s = {s};  // 2^-32",
        "    const auto x = static_cast<T>(phase) * s;",
        "    const auto xm1 = -static_cast<T>(std::uint32_t{0} - phase) * s;",
        "    const auto u = static_cast<T>(static_cast<std::int32_t>(phase - 0x80000000u)) * s;",
        "    const auto u2 = u * u;",
        *_horner("p", fit_cheb_turns(degree), "u2"),
        "    return -u * x * xm1 * p;",
    ]
    return name, _function(name, [
        f"sin(2 pi phase / 2^32) from a 32-bit phase accumulator, Chebyshev degree {degree}.",
        "x, x - 1 and u = x - 1/2 each come straight from the integer, so all three",
        "zeros keep full relative precision (cf. cheb_turns_phase, which converts once).",
    ], body, arg="std::uint32_t phase")


