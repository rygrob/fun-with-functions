def emit_db_to_gain(degree, safe, pinned=True):
    from .dbpoly import K, fit_gain
    name = f"db_to_gain_{degree}" + ("_safe" if safe else "") + ("" if pinned else "_free")
    head = [f"    {'auto' if safe else 'const auto'} t = db * {lit(K)};"]
    if safe:
        head.append("    t = std::clamp(t, T(-151), T(128));  // -inf dB clamps too; 2^-151 rounds to 0")
