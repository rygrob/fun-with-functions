def emit_exp_cody_waite(degree):
    from .exppoly import LN2, LOG2E, fit_exp, split_ln2
    hi32, lo32 = (float(v) for v in split_ln2(np.float32))
    hi64, lo64 = (float(v) for v in split_ln2(np.float64))
    name = f"cody_waite_exp_{degree}"
    body = [
        f"    constexpr auto ln2_hi = std::is_same_v<T, float> ? {lit(hi32)} : {lit(hi64)};",
        f"    constexpr auto ln2_lo = std::is_same_v<T, float> ? {lit(lo32)} : {lit(lo64)};",
        f"    const auto n = std::nearbyint(x * {lit(LOG2E)});",
        "    const auto r = (x - n * ln2_hi) - n * ln2_lo;  // breaks under reassociation",
        *_horner("p", fit_exp(degree), "r"),
        "    return pow2i<T>(static_cast<ieee_int<T>>(n)) * p;",
    ]
    return name, _function(name, [
        f"e^x = 2^n * P(r), n = round(x / ln 2), r = x - n ln 2 by Cody–Waite (ln 2 split hi + lo); degree {degree}.",
        f"Results normal for |x| below ~87 (float). r in [-{LN2 / 2:.4f}, {LN2 / 2:.4f}].",
    ], body)


