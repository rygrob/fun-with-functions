def _fold_name(fold):
    return "mantissa" if fold is None else "fold15" if fold == 1.5 else "foldsqrt2"


def _fold_lines(fold):
    """Read e and m; optionally fold m >= fold down by an octave (then they're
    reassigned, so not const)."""
    kw = "const auto" if fold is None else "auto"
    lines = [
        "    auto ei = ieee_int<T>{0};",
        f"    {kw} m = split_exponent(x, ei);",
        f"    {kw} e = static_cast<T>(ei);",
    ]
    if fold is not None:
        lines += [
            f"    const auto big = m >= {lit(fold)};",
            "    m = big ? m * T(0.5) : m;",
            "    e = big ? e + T(1) : e;",
        ]
    return lines


def emit_log2(degree, fold):
    from .log2poly import fit_mantissa, fold_range
    name = f"{_fold_name(fold)}_log2_{degree}"
    lo, hi = fold_range(fold)
    body = [
        *_fold_lines(fold),
        "    const auto u = m - T(1);",
        *_horner("p", fit_mantissa(degree, fold), "u"),
        "    return e + u * p;",
    ]
    return name, _function(name, [
        f"log2(x) = e + u * P(u), x = 2^e * m, u = m - 1 in [{lo:.4f}, {hi:.4f}); degree {degree}.",
        "x positive and normal." + ("" if fold is not None else " Cancels for x just below 1 (e = -1, m ~ 2)."),
    ], body)


def emit_log2_atanh(degree):
    from .log2poly import SQRT2, fit_atanh
    name = f"atanh_log2_{degree}"
