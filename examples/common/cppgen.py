def emit_tanh_sigmoid(degree, coeffs=None, name=None, clamp=None):
    """s / sqrt(1 + s^2); coeffs default to the sech^3-weighted Remez fit.
    With clamp, x is clamped to ±clamp first (fmin / fmax: two instructions,
    vectorizable) and y is s / sqrt; without it, the vsl-style s * (1 / sqrt)."""
    from .tanhpoly import fit_sigmoid
    r = fit_sigmoid(degree) if coeffs is None else coeffs
    if clamp is None:
        name = name or f"sigmoid_tanh_{degree}"
        return name, _function(name, [
            f"tanh(x) ~ s / sqrt(1 + s^2), s = x * R(x^2) ~ sinh x, degree {degree}.",
            "|y| < 1 and monotonic by construction. s * s overflows for |x| beyond ~500 (float): y -> 0.",
        ], [
            "    const auto x2 = x * x;",
            *_horner("r", r, "x2"),
            "    const auto s = x * r;",
            "    return s * (T(1) / std::sqrt(s * s + T(1)));  // rsqrt form, as vsl",
        ])
    name = name or f"sigmoid_clamp_tanh_{degree}"
    return name, _function(name, [
        f"tanh(x) ~ s / sqrt(1 + s^2), s = x * R(x^2) ~ sinh x, degree {degree}, x clamped to ±{clamp:g}.",
        f"tanh rounds to 1 in float past ~9.01, so the clamp costs nothing and s * s can't overflow.",
    ], [
        f"    const auto xc = std::fmin(std::fmax(x, T({-clamp!r})), T({clamp!r}));",
        "    const auto x2 = xc * xc;",
        *_horner("r", r, "x2"),
        "    const auto s = xc * r;",
        "    return s / std::sqrt(s * s + T(1));",
    ])


def emit_tanh_pade(m, n, clamp=None):
    """Output clamped to ±1 (JUCE-style; inf / inf = NaN past ~1e7 slips
    through), or with clamp, x clamped to ±clamp first like the sigmoid."""
    from .tanhpoly import pade_tanh
    pe, qe = pade_tanh(m, n)
    if clamp is None:
        name = f"pade_tanh_{m}_{n}"
        return name, _function(name, [
            f"tanh(x) ~ x * P(x^2) / Q(x^2), Padé [{m}/{n}], clamped: an odd rational has no horizontal asymptote.",
        ], [
            "    const auto x2 = x * x;",
            *_horner("p", [float(c) for c in pe], "x2"),
            *_horner("q", [float(c) for c in qe], "x2"),
            "    return std::clamp(x * p / q, T(-1), T(1));",
        ])
    name = f"pade_clamp_tanh_{m}_{n}"
    return name, _function(name, [
        f"tanh(x) ~ x * P(x^2) / Q(x^2), Padé [{m}/{n}], x clamped to ±{clamp:g}: past it the rational",
        "climbs through 1, and the clamp keeps x^2 small, so P and Q can't overflow.",
    ], [
        f"    const auto xc = std::fmin(std::fmax(x, T({-clamp!r})), T({clamp!r}));",
        "    const auto x2 = xc * xc;",
        *_horner("p", [float(c) for c in pe], "x2"),
        *_horner("q", [float(c) for c in qe], "x2"),
        "    return xc * p / q;",
    ])


