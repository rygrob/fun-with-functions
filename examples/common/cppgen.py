def bit_helpers():
    """The IEEE field layout as traits, and pow2i and split_exponent written
    once over it for float and double; emitted once per header."""
    return """/// IEEE 754 field layout, in integers as wide as T: the bits unsigned and
/// signed, the stored significand bits (one more is implicit), the exponent
/// bits and the bias.
template<typename T>
struct ieee;

template<>
struct ieee<float>
{
    using bits = std::uint32_t;
    using sbits = std::int32_t;
    static constexpr auto sig_bits = bits{23};
    static constexpr auto exp_bits = bits{8};
    static constexpr auto bias = sbits{127};
};

template<>
struct ieee<double>
{
    using bits = std::uint64_t;
    using sbits = std::int64_t;
    static constexpr auto sig_bits = bits{52};
    static constexpr auto exp_bits = bits{11};
    static constexpr auto bias = sbits{1023};
};

/// The signed integer as wide as T: exponents and the integer parts of x.
template<typename T>
using ieee_int = typename ieee<T>::sbits;

/// 2^n by writing the exponent field: (n + bias) << significand bits.
/// Exact for n in the normal range (float: [-126, 127]); outside it wraps.
template<typename T>
inline auto pow2i(ieee_int<T> n) -> T
{
    using F = ieee<T>;
    using U = typename F::bits;
    const auto biased = static_cast<U>(n + F::bias);
    const auto field = biased << F::sig_bits;
    return std::bit_cast<T>(field);
}

/// x = 2^e * m with m in [1, 2), for positive normal x: e from the exponent
/// field, m from the significand with the exponent field set to 2^0.
template<typename T>
inline auto split_exponent(T x, ieee_int<T>& e) -> T
{
    using F = ieee<T>;
    using U = typename F::bits;
    using I = typename F::sbits;
    constexpr auto sig_mask = (U{1} << F::sig_bits) - U{1};
    constexpr auto exp_mask = (U{1} << F::exp_bits) - U{1};
    const auto b = std::bit_cast<U>(x);
    e = static_cast<I>((b >> F::sig_bits) & exp_mask) - F::bias;
    const auto zero_exp = static_cast<U>(F::bias) << F::sig_bits;
    return std::bit_cast<T>((b & sig_mask) | zero_exp);
}
"""


def split_exponent_float():
    """split_exponent for float alone, every type and constant written out:
    the step before the generic ieee<T> form (slides only). The same e and m
    as split_exponent<float> on every float."""
    return """inline auto split_exponent(float x, std::int32_t& e) -> float
{
    const auto b = std::bit_cast<std::uint32_t>(x);
    e = static_cast<std::int32_t>((b >> 23) & 0xFFu) - 127;
    return std::bit_cast<float>((b & 0x7FFFFFu) | (127u << 23));
}
"""

def emit_exp2_bits(tuned):
    from .exp2poly import bits_offset
    name = "bits_exp2" + ("_tuned" if tuned else "")
    off = bits_offset() if tuned else 0.0
    body = [
        f"    const auto t = std::trunc((x + {lit(off)}) * T(0x1p23));" if tuned else
        "    const auto t = std::trunc(x * T(0x1p23));",
        "    return std::bit_cast<float>(static_cast<std::uint32_t>(static_cast<std::int32_t>(t) + (127 << 23)));",
    ]
    return name, _function(name, [
        "2^x by Schraudolph's trick: x * 2^23 written into the bits, so the significand",
        "holds the fraction and 2^f ~ 1 + f." + (" Offset tuned for minimax relative error." if tuned else ""),
        "float only; x in the normal range.",
    ], body)


def emit_exp2(degree, reduction):
    from .exp2poly import fit_exp2
    name = f"{reduction}_exp2_{degree}"
    body = [
        f"    const auto r = std::{'floor' if reduction == 'floor' else 'nearbyint'}(x);",
        "    const auto f = x - r;",
        *_horner("p", fit_exp2(degree, reduction), "f"),
        "    return pow2i<T>(static_cast<ieee_int<T>>(r)) * p;",
    ]
    lo, hi = ("0", "1)") if reduction == "floor" else ("-1/2", "1/2]")
    return name, _function(name, [
        f"2^x = 2^n * P(f), n = {reduction}(x), f in [{lo}, {hi}; P a degree-{degree} Chebyshev fit of 2^f.",
        "x must keep n in the normal range (float: x in [-126, 127]).",
    ], body)


def emit_exp2_unit(degree):
    from .exp2poly import fit_exp2_unit
    name = f"round_unit_exp2_{degree}"
    body = [
        "    const auto r = std::nearbyint(x);",
        "    const auto f = x - r;",
        *_horner("q", fit_exp2_unit(degree), "f"),
        "    const auto p = T(1) + f * q;",
        "    return pow2i<T>(static_cast<ieee_int<T>>(r)) * p;",
    ]
    return name, _function(name, [
        f"2^x = 2^n * (1 + f Q(f)), n = round(x), f in [-1/2, 1/2]; Q a degree-{degree - 1} Chebyshev fit, so 1 + f Q has degree {degree}.",
        "Exact at every integer x. x must keep n in the normal range (float: x in [-126, 127]).",
    ], body)


def emit_exp2_table(degree, size):
    from .exp2poly import fit_table
    name = f"table_exp2_{degree}_{size}"
    shift = size.bit_length() - 1
    values = np.exp2(np.arange(size) / size)
    rows = ["    static constexpr T table[] = {"]
    for i in range(0, size, 4):
        rows.append("        " + " ".join(f"{lit(v)}," for v in values[i:i + 4]))
    rows.append("    };")
    body = [
        *rows,
        f"    const auto kf = std::nearbyint(x * T({size}));",
        f"    const auto f = x - kf * T({1.0 / size!r});",
        "    const auto k = static_cast<ieee_int<T>>(kf);",
        f"    const auto t = table[k & {size - 1}];",
        *_horner("q", fit_table(degree, size), "f"),
        f"    return pow2i<T>(k >> {shift}) * (t + t * (f * q));",
    ]
    return name, _function(name, [
        f"2^x = 2^n * 2^(j/{size}) * (1 + f Q(f)): k = round({size} x), n = k >> {shift}, j = k & {size - 1},",
        f"f in [-1/{2 * size}, 1/{2 * size}]; Q a degree-{degree - 1} Chebyshev fit, so 1 + f Q has degree {degree}.",
    ], body)


