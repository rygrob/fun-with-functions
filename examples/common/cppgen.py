"""Emit C++ for the sin approximations.

Every function is a template on T (float or double), so one emitted
function covers both precisions. Constants are emitted as 17-significant-
digit double literals wrapped in T(...): for T = float the conversion rounds
to nearest, which is exactly np.float32(c) in the Python model.

The emitted code is plain multiply-adds (p * x2 + c). Whether the compiler
fuses those into FMAs depends on its -ffp-contract default; the Python model
never fuses, so results can differ by a rounding or so per step.
"""

import math

import numpy as np

from .metrics import PI


def lit(c):
    """T(<double literal>) that round-trips c exactly as a double."""
    return f"T({float(c)!r})"


def prologue():
    return """#pragma once
// Generated by bench/generate.py from the Python examples -- do not edit.

#include <cmath>
#include <cstdint>
#include <type_traits>

namespace adc {
"""


def epilogue():
    return "\n} // namespace adc\n"


def _horner(var, coeffs, t, indent="    "):
    """Lines evaluating sum coeffs[k] * t^k into `var` by Horner."""
    lines = [f"{indent}auto {var} = {lit(coeffs[-1])};"]
    for c in reversed(coeffs[:-1]):
        lines.append(f"{indent}{var} = {var} * {t} + {lit(c)};")
    return lines


def _function(name, doc, body, arg="T x"):
    doc_lines = [f"/// {d}" if d else "///" for d in doc]
    return "\n".join(doc_lines + [
        "template<typename T>",
        f"inline auto {name}({arg}) -> T",
        "{",
        *body,
        "}",
        "",
    ])


def odd_poly(name, coeffs, doc):
    """x * P(x^2) -- Taylor and vanilla Chebyshev."""
    body = ["    const auto x2 = x * x;", *_horner("p", coeffs, "x2"), "    return x * p;"]
    return _function(name, doc, body)


def pade(name, pe, qe, doc):
    """x * P(x^2) / Q(x^2)."""
    body = [
        "    const auto x2 = x * x;",
        *_horner("p", [float(c) for c in pe], "x2"),
        *_horner("q", [float(c) for c in qe], "x2"),
        "    return x * p / q;",
    ]
    return _function(name, doc, body)


def factored(name, p, doc):
    """(x - pi)(x + pi) * P(x^2) * x with a single pi constant."""
    body = [
        f"    constexpr auto pi = {lit(PI)};",
        "    const auto x2 = x * x;",
        *_horner("p", p, "x2"),
        "    return (x - pi) * (x + pi) * p * x;",
    ]
    return _function(name, doc, body)


def split(name, p, doc):
    """((x - pi_hi) - pi_lo)((x + pi_hi) + pi_lo) * P(x^2) * x."""
    lo32 = float(np.float32(PI - float(np.float32(PI))))
    lo64 = math.sin(math.pi)  # pi - fl64(pi), see sinpoly.split_pi
    body = [
        f"    constexpr auto pi_hi = {lit(PI)};",
        f"    constexpr auto pi_lo = std::is_same_v<T, float> ? {lit(lo32)} : {lit(lo64)};",
        "    const auto x2 = x * x;",
        *_horner("p", p, "x2"),
        "    const auto lo = (x - pi_hi) - pi_lo;  // ~ x - pi; breaks under reassociation",
        "    const auto hi = (x + pi_hi) + pi_lo;  // ~ x + pi",
        "    return lo * hi * p * x;",
    ]
    return _function(name, doc, body)


def fp_precise_macros():
    """Guards that keep a function's FP semantics precise under -ffast-math
    and /fp:fast, and keep it inlined: tested for MSVC and clang(-cl) in
    github.com/rygrob/adc-msvc. MSVC tracks the FP model per function and
    won't auto-inline a precise function into a fast caller, so it needs
    __forceinline; clang flags each instruction, so the pragma alone would
    do, and always_inline just matches. GCC has neither pragma: unguarded."""
    return """#if defined(_MSC_VER)
    #define FP_PRECISE_BEGIN __pragma(float_control(precise, on, push))
    #define FP_PRECISE_END   __pragma(float_control(pop))
    #define FP_FORCEINLINE   __forceinline
#elif defined(__clang__)
    #define FP_PRECISE_BEGIN _Pragma("float_control(precise, on, push)")
    #define FP_PRECISE_END   _Pragma("float_control(pop)")
    #define FP_FORCEINLINE   inline __attribute__((always_inline))
#else
    #define FP_PRECISE_BEGIN
    #define FP_PRECISE_END
    #define FP_FORCEINLINE   inline
#endif
"""


def fp_precise(code):
    """An emitted function, guarded: FP_PRECISE_BEGIN / END around it and
    FP_FORCEINLINE for inline (see fp_precise_macros)."""
    assert code.count("inline auto ") == 1
    return "FP_PRECISE_BEGIN\n" + code.replace("inline auto ", "FP_FORCEINLINE auto ").rstrip("\n") + "\nFP_PRECISE_END\n"


def turns(name, p, doc):
    """sin(2 pi x), x in [0, 1]: -u * x * (x - 1) * P(u^2), u = x - 1/2."""
    body = [
        "    const auto u = x - T(0.5);",
        "    const auto u2 = u * u;",
        *_horner("p", p, "u2"),
        "    return -u * x * (x - T(1)) * p;",
    ]
    return _function(name, doc, body)


def lut_table(size, values):
    """Namespace-scope variable template holding size + 1 entries."""
    rows = []
    for i in range(0, len(values), 4):
        rows.append("    " + " ".join(f"{lit(v)}," for v in values[i:i + 4]))
    return "\n".join([
        f"/// sin(-pi + 2 pi i / {size}), i = 0..{size} (last entry is a guard point)",
        "template<typename T>",
        f"inline constexpr T sin_table_{size}[{size + 1}] = {{",
        *rows,
        "};",
        "",
    ])


def _check_pow2(size):
    if size & (size - 1):
        raise ValueError(f"C++ LUT emission needs a power-of-two size, got {size}")


def lut(name, size, interp, doc, table_expr=None):
    """Nearest or linear lookup, radians in. size must be a power of two so
    the index wrap is a mask, as it would be in practice. table_expr names
    the table (default: the literal sin_table_<size> from lut_table)."""
    _check_pow2(size)
    head = [
        f"    constexpr auto pi = {lit(PI)};",
        f"    constexpr auto scale = {lit(size / (2 * PI))};  // N / 2pi",
        f"    const auto& t = {table_expr or f'sin_table_{size}<T>'};",
        "    const auto pos = (x + pi) * scale;",
    ]
    if interp == "nearest":
        # pos + 0.5 > 0 on the whole range, so truncation is floor.
        body = head + [
            f"    const auto i = static_cast<std::uint32_t>(static_cast<std::int32_t>(pos + T(0.5)) & {size - 1});",
            "    return t[i];",
        ]
    else:
        # floor, not truncation: x = f32(-pi) gives pos slightly below 0.
        body = head + [
            "    const auto fl = std::floor(pos);",
            "    const auto frac = pos - fl;",
            f"    const auto i = static_cast<std::uint32_t>(static_cast<std::int32_t>(fl) & {size - 1});",
            "    return t[i] + frac * (t[i + 1] - t[i]);",
        ]
    return _function(name, doc, body)


def lut_phase(name, size, interp, doc, table_expr):
    """Lookup from a 32-bit fixed-point phase accumulator (0 .. 2^32 = one
    turn), the way a shipped table oscillator does it: the top log2(size)
    bits are the index, the rest the fraction. No float index math, and the
    wrap is free (unsigned overflow). table_expr holds sin(2 pi i / size)."""
    _check_pow2(size)
    bits = size.bit_length() - 1
    shift = 32 - bits
    body = [f"    const auto& t = {table_expr};"]
    if interp == "nearest":
        # Round to nearest entry; phases in the top half-step wrap to entry 0.
        body += [
            f"    const auto i = (phase + (std::uint32_t{{1}} << {shift - 1})) >> {shift};",
            "    return t[i];",
        ]
    else:
        body += [
            f"    const auto i = phase >> {shift};",
            f"    const auto frac = static_cast<T>(phase & {hex((1 << shift) - 1)}u) * {lit(2.0 ** -shift)};",
            "    return t[i] + frac * (t[i + 1] - t[i]);",
        ]
    return _function(name, doc, body, arg="std::uint32_t phase")


